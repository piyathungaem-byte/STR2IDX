"""Write a VobSub pair (.idx index + .sub MPEG-PS subtitle stream)."""
from __future__ import annotations

from dataclasses import dataclass

from . import spu

# 16-colour DVD palette. Entry 0 is never drawn (it is the transparent code 0),
# entry 1 is body text, entry 2 the outline/shadow. Everything else is filler
# so that players which ignore our colormap still see sane colours.
DEFAULT_PALETTE = [
    0x000000,  # 0 transparent background
    0xF0F0F0,  # 1 body text (near-white)
    0x101010,  # 2 outline (near-black)
    0x000000,  # 3
    0x0000FF, 0x00FF00, 0xFF0000, 0xFFFF00,
    0xFF00FF, 0x00FFFF, 0x808000, 0x8080FF,
    0x800080, 0x80FF80, 0x008080, 0xAAAAAA,
]


@dataclass
class VobSubOptions:
    substream_id: int = 0x20      # 0x20..0x3f are DVD subpicture streams
    language: str = "eng"
    title: str = "srt2idx"
    palette: list[int] | None = None
    # colormap[code] -> palette index; alpha[nibble] where 0xF == opaque
    colormap: tuple[int, int, int, int] = (0, 1, 2, 3)
    alpha: tuple[int, int, int, int] = (0x0, 0xF, 0xF, 0xF)


def _ts(ms: int) -> str:
    h, rem = divmod(max(0, ms), 3_600_000)
    m, rem = divmod(rem, 60_000)
    s, milli = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d}:{milli:03d}"


def build(
    spu_packets: list[tuple[int, bytes]],
    canvas: tuple[int, int],
    options: VobSubOptions,
) -> tuple[bytes, bytes]:
    """Return (idx_bytes, sub_bytes)."""
    palette = options.palette or DEFAULT_PALETTE
    if len(palette) != 16:
        raise ValueError("palette must have exactly 16 entries")

    sub_bytes, offsets = spu.build_sub_stream(spu_packets, options.substream_id)

    # tridx mirrors the alpha nibbles we put in the SPU stream: colour code 0
    # is transparent, 1..3 opaque.  Players read the stream, not this hint,
    # but tools that do look at it should not be told something else.
    tridx = "".join("0" if a == 0 else "F" for a in options.alpha)
    lines = [
        "# VobSub index file, v7 (do not modify this line!)",
        "# Generated by srt2idx from SubRip input.",
        f"size: {canvas[0]}x{canvas[1]}",
        "palette: " + ", ".join(f"{c:06x}" for c in palette),
        "custom colors: ON, tridx: " + tridx + ", colors: "
        + ", ".join(f"{palette[i]:06x}" for i in options.colormap),
        "langidx: 0",
        f"id: {options.language}, index: {options.substream_id - 0x20}",
        f"alt: {options.title}",
    ]
    for (start_ms, _), pos in zip(spu_packets, offsets):
        lines.append(f"timestamp: {_ts(start_ms)}, filepos: {pos:09x}")

    # UTF-8 without BOM: FFmpeg reads alt: as raw metadata bytes, and every
    # modern player that shows a language name in its subtitle menu handles
    # UTF-8.  Only the structural fields (size/palette/timestamps/id) are
    # ever parsed as ASCII, and those stay pure ASCII by construction.
    idx = ("\n".join(lines) + "\n").encode("utf-8")
    return idx, sub_bytes
